std::optional<uint16_t> media_type_to_content_format(const std::string& media_type) {
    auto it = kMediaTypeToContentFormat.find(media_type);
    if (it == kMediaTypeToContentFormat.end()) return std::nullopt;
    return it->second;
}

std::optional<std::string> content_format_to_media_type(uint16_t cf) {
    auto it = kContentFormatToMediaType.find(cf);
    if (it == kContentFormatToMediaType.end()) return std::nullopt;
    return it->second;
}

